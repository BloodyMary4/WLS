import { CharacterStats, GameEvent } from '../types';

/**
 * Лорная ветка «Путь Гретчина» (v0.3.16).
 * Гретчины — маленькая прислужливая раса, которую орки считают рабами и
 * бьют без повода; при этом они умеют говорить на орочьем, чинят оружие
 * и оружие «грат» и в больших скоплениях способны на самоорганизацию.
 * Ветка открывается ключевым выбором `grot_uprising` (восстание гретчинов
 * в обычном орочьем/гретчинском событии) и ведёт жизнь от раба до
 * вожака собственного племени. Тексты используют формат 'Возраст N. ...'
 * — совместим с фильтрацией летописи на экране смерти.
 */

export function getGretchinBranchEvent(age: number, c: CharacterStats): GameEvent | null {
  // Шаг 3: племя принято — первое испытание вожака
  if (age >= 35 && c.keyChoices.includes('grot_chieftain')) {
    return {
      text: 'Возраст ' + age + '. Твоё племя грат-лидеров признала. Но признание надо кормить: разведка приносит весть — старый Босс Грозлык идёт «проверить, не завели ли рабы лишнего». У вас есть выбор, как встретить зелёного.',
      choices: [
        { letter: '1', text: 'Отдать дань: оружие, еда, несколько воров-добытчиков', effects: { cunning: 2, credits: -15, influence: 1, keyChoice: 'grot_tribute', description: 'Грозлык ухмыляется: «РАБЫ СТАЛИ ПОЛЕЗНЫ». Племя выживает. Ты копишь злобу молча.' } },
        { letter: '2', text: 'Заминировать тропу грат-минами', effects: { techSkill: 3, health: -8, newStatus: 'Вожак-диверсант', keyChoice: 'grot_tribute', description: 'Взрывы гремят всю ночь. Грозлык отступает, потеряв половину бойз. Орки запомнят: с гретчинами шутки плохи.' } },
        { letter: '3', text: 'Бежать к людям — предложить им карту лагерей', effects: { sneakiness: 3, suspicion: 2, newStatus: 'Разведчик Империума', keyChoice: 'grot_tribute', description: 'Люди удивлены говорящим гретчином, но карта стоит крови. Теперь ты между двух огней.' } },
        { letter: '4', text: 'Вызвать Грозлыка на «честную драку» — по их же правилам', effects: { strength: 2, willpower: 3, health: -18, keyChoice: 'grot_duel', description: 'Ты мелкий, но правила Waaagh! святы: вызов принят. Первый удар — за тобой. Дальше — как повезёт.' } },
      ]
    };
  }

  // Шаг 2: после восстания — consolidation племени
  if (age >= 25 && c.keyChoices.includes('grot_uprising')) {
    return {
      text: 'Возраст ' + age + '. Восстание удалось — лагерь пуст, зеленые разбежались кто куда. Но свобода пахнет навозом: сотни грат смотрят на тебя и ждут приказа. Кто-то должен стать вожаком. Ты?',
      choices: [
        { letter: '1', text: 'Принять жезл — стать вожаком племени грат', effects: { influence: 3, willpower: 2, newStatus: 'Вожак грат', keyChoice: 'grot_chieftain', description: 'Ты вскидываешь краденый чоппа. «ДА!» — ревёт толпа мелких голосов. С этого дня у гретчинов есть своё слово.' } },
        { letter: '2', text: 'Увести всех в подземные тоннели — строить тайный город', effects: { cunning: 3, techSkill: 2, health: -4, keyChoice: 'grot_warrens', description: 'Под корнями мира-обломка вы ройте новые ходы. Орки ищут рабов наверху — а внизу растает Grot-град.' } },
        { letter: '3', text: 'Разделить племя на отряды и рассредоточить по миру', effects: { sneakiness: 2, influence: -1, keyChoice: 'grot_scatter', description: 'Кто-то к тау, кто-то к людям, кто-то в космос. Разобщённость — тоже защита. Выживет хотя бы часть.' } },
        { letter: '4', text: 'Отказаться от власти — пусть выбирают сами', effects: { unity: 3, faith: 1, keyChoice: 'grot_council', description: 'Ты ставишь чашу на землю: «Решайте сами». Грат решают — шумно, драчно, но честно. Совет мелких вожаков.' } },
      ]
    };
  }

  // Шаг 1: искра — несправедливость, после которой можно подняться
  if (age >= 15 && !c.keyChoices.includes('grot_uprising') && !c.keyChoices.includes('grot_leader_path')) {
    return {
      text: 'Возраст ' + age + '. Старый грат по кличке Хнык умер на шахте — его загнали ладом за упавший ящик боеприпасов. Боссы смеются. Ночью в бараке шепчутся: «Хватит». Все смотрят на тебя — того, кто чинит пушки и знает, где лежат взрывчатки.',
      choices: [
        { letter: '1', text: 'Возглавить ночной саботаж — подорвать склад, уйти в канализацию', effects: { techSkill: 3, sneakiness: 2, health: -6, newStatus: 'Предводитель грат', keyChoice: 'grot_uprising', description: 'Склад взлетает синим пламенем. На утро лагерь в хаосе, а в сточных тоннелях горят факелы и собираются первые сотни свободных грат.' } },
        { letter: '2', text: 'Организовать тихое восстание — «работаем, но делаем всё сломанным»', effects: { cunning: 3, unity: 2, keyChoice: 'grot_uprising', description: 'Ни один девайс орков не держится и недели. Боссы в ярости, бойз ворчат. Медленно, без крови, вы становитесь незаменимыми.' } },
        { letter: '3', text: 'Собрать совет старейшин грат — решать всем вместе', effects: { influence: 2, unity: 3, keyChoice: 'grot_leader_path', description: 'Двенадцать морщинистых грат садятся в круг. Решения принимаются долго — зато их слушают даже те, кого не били сегодня.' } },
        { letter: '4', text: 'Не рисковать — выжить самому, остальное потом', effects: { sneakiness: 2, willpower: -1, description: 'Ты отводишь глаза. Через месяц Хныка забывают, а тебя ставят начальником над новой партией рабов. Ты теперь тоже бьёшь.' } },
      ]
    };
  }

  return null;
}
