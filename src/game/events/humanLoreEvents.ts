// Анти-повторная машина (v0.3.77): раньше лорные выборы повторялись, потому что
// пул был маленький и выбирался случайно с возвратом. Теперь:
// 1) помечаем просмотренные события прямо в keyChoices персонажа ('loreN') —
//    они сохраняются в сейве и переживают перезагрузку страницы;
// 2) пока есть непросмотренные — берём только из них;
// 3) когда все просмотрены — крутим полный цикл без повторов подряд (перемешанная
//    колода), тасуя заново при её опустошении.
export function markLoreSeen(c: CharacterStats, idx: number): void {
  const tag = 'lore' + idx;
  if (!c.keyChoices) c.keyChoices = [];
  if (!c.keyChoices.includes(tag)) c.keyChoices.push(tag);
}

function shuffle<T>(arr: T[]): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rng().next() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

export function getHumanLoreEvent(age: number, c: CharacterStats): GameEvent | null {
  const all = LORE_POOL.map((e, i) => ({ e, i })).filter(
    ({ e }) => age >= e.minAge && (!e.planet || e.planet.includes(c.planetType)) && (!e.cond || e.cond(c)),
  );
  if (all.length === 0) return null;
  // На «пятых» годах чаще брать лорное событие, иначе — реже, чтобы не вытеснять ветки
  const roll = rng().next();
  const takeChance = age % 5 === 0 ? 0.55 : 0.2;
  if (roll > takeChance) return null;

  const seen = c.keyChoices ?? [];
  const virgin = all.filter(({ i }) => !seen.includes('lore' + i));
  let chosen: { e: (typeof LORE_POOL)[number]; i: number };
  if (virgin.length > 0) {
    chosen = virgin[Math.floor(rng().next() * virgin.length)];
  } else {
    // Полный цикл: перемешанная колода (внутри неё повторов нет по построению)
    chosen = shuffle(all)[0];
    // Сбрасываем историю показов этого пула и стартуем новый круг
    c.keyChoices = seen.filter((k) => !all.some(({ i }) => 'lore' + i === k));
  }
  markLoreSeen(c, chosen.i);
  const body = chosen.e.ev.text.split('%AGE%').join(String(age));
  // Маркер индекса пула — его вырезает stripLoreMarker перед показом; reducer отмечает просмотр.
  return { ...chosen.e.ev, text: `\u200B${chosen.i}\u200B` + body };
}

/** Убирает служебный маркер «\u200Bidx\u200B» из текста лорного события. */
export function stripLoreMarker(text: string): string {
  return text.replace(/^\u200B\d+\u200B/, '');
}

/** Индекс события лорного пула из маркера (или null). */
export function loreMarkerIndex(text: string): number | null {
  const m = /^\u200B(\d+)\u200B/.exec(text);
  return m ? Number(m[1]) : null;
}
