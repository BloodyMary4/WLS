/** Порог критического дефицита провизии (голод наступает при 0). */
export const FOOD_CRITICAL = 1;
/** Голод активен: есть нечего. */
export function isStarving(food: number): boolean {
  return food <= 0;
}


/** Ограничение значения скрытой характеристики шкалы 0–10 (защита полосы от «вылета»). */
export function clampStat(value: number): number {
  if (!Number.isFinite(value)) return 0;
  return Math.max(0, Math.min(10, value));
}

/** Плюрализация слова «год»: 1 год / 2-4 года / 5+ лет (включая 21, 101...). */
export function declineYear(n: number): string {
  const m10 = n % 10, m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return 'год';
  if (m10 >= 2 && m10 <= 4 && (m100 < 10 || m100 >= 20)) return 'года';
  return 'лет';
}

