/** Человекочитаемая подпись к запасу провизии: «хватит на 2 года» / «Последний паёк!». */
export function foodCaption(food: number): string {
  if (isStarving(food)) return 'Еды нет!';
  if (food <= FOOD_CRITICAL) return 'Последний паёк!';
  return `хватит на ${food} ${declineYear(food)}`;
}
